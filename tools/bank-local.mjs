#!/usr/bin/env node
/**
 * Install the local full course bank into the build.
 *
 *   data/bank.json  (git-ignored, provided by the user)
 *        -> data/local-bank.json  (git-ignored build input)
 *        -> src/lib/local-bank.generated.ts  (git-ignored, imported by src/lib/bank.ts)
 *
 * Without a local bank it writes a null-loading shim, so `npm install && npm run build`
 * works in a clean checkout with only the bundled demo bank.
 *
 * Usage:  npm run bank:local
 */
import { readFile, writeFile, mkdir, access } from 'node:fs/promises'
import { constants } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const SRC = path.join(ROOT, 'data', 'bank.json')
const OUT_DATA = path.join(ROOT, 'data', 'local-bank.json')
const OUT_TS = path.join(ROOT, 'src', 'lib', 'local-bank.generated.ts')

const SHIM = `// AUTO-GENERATED by tools/bank-local.mjs — do not edit, do not commit.
import type { BankData } from './types'
export const LOCAL_BANK: BankData | null = null
`

async function exists(p) {
  try {
    await access(p, constants.R_OK)
    return true
  } catch {
    return false
  }
}

function validateBank(data) {
  const errors = []
  if (!data || typeof data !== 'object') return ['不是 JSON 对象']
  if (typeof data.schema !== 'string') errors.push('缺少 schema')
  if (!Array.isArray(data.chapterOrder) || data.chapterOrder.length === 0) errors.push('chapterOrder 为空')
  if (!Array.isArray(data.questions) || data.questions.length === 0) return errors.concat(['questions 为空'])
  const seen = new Set()
  for (const q of data.questions) {
    if (typeof q?.id !== 'string' || !q.id) {
      errors.push('存在缺少 id 的题目')
      break
    }
    if (seen.has(q.id)) errors.push(`重复 id: ${q.id}`)
    seen.add(q.id)
    if (typeof q.stem !== 'string' || !q.stem.trim()) errors.push(`${q.id} 题干为空`)
    if (!['single', 'multi', 'judge', 'short', 'material'].includes(q.type)) errors.push(`${q.id} 题型非法: ${q.type}`)
    if (q.type === 'single' || q.type === 'multi') {
      if (!Array.isArray(q.options) || q.options.length < 2) errors.push(`${q.id} 选项不足`)
      if (typeof q.answerNorm !== 'string') errors.push(`${q.id} 客观题缺少 answerNorm`)
    }
    if (q.type === 'judge' && typeof q.answerNorm !== 'boolean') errors.push(`${q.id} 判断题 answerNorm 应为布尔值`)
  }
  return errors
}

const hasSrc = await exists(SRC)
// `--ensure` is the idempotent form used by `postinstall`: create the loader only
// when it is missing, so a developer who already installed the full bank is not
// silently downgraded to the sample bank by an unrelated `npm install`.
const ensureOnly = process.argv.includes('--ensure')
// `--public` force-writes the null shim even when a full bank is present. It is
// the explicit "I am producing a public artefact" switch: building for release on
// a machine that also holds the licensed bank must not embed it.
const forcePublic = process.argv.includes('--public')

if (forcePublic) {
  await writeFile(OUT_TS, SHIM, 'utf-8')
  console.log('[bank:local] --public：已写入示例题库加载器（公开构建模式）')
  if (hasSrc) {
    console.log('[bank:local] 注意：检测到 data/bank.json，但本次构建不会包含它（公开交付）')
  }
  process.exit(0)
}

if (!hasSrc) {
  if (ensureOnly && (await exists(OUT_TS))) {
    console.log('[bank:local] 加载器已存在，保持现状')
    process.exit(0)
  }
  await writeFile(OUT_TS, SHIM, 'utf-8')
  console.log('[bank:local] 未找到 data/bank.json —— 已写入示例题库加载器（公开构建模式）')
  console.log('[bank:local] 提示：将完整题库放到 data/bank.json 后重新运行本命令即可启用完整题库')
  process.exit(0)
}
if (ensureOnly && (await exists(OUT_TS))) {
  // A full bank is installed and a loader already exists. Regenerating on every
  // `npm install` would be wasted work, so leave it alone; the explicit
  // `npm run bank:local` is the way to rebuild after the bank changes.
  console.log('[bank:local] 检测到 data/bank.json，跳过自动生成（需要重建请显式运行 npm run bank:local）')
  process.exit(0)
}
// Otherwise fall through and generate: a full bank with no loader yet (a fresh
// clone plus a dropped-in bank) still needs one, and `--ensure` must produce it.

const raw = await readFile(SRC, 'utf-8')
let data
try {
  data = JSON.parse(raw)
} catch (e) {
  console.error(`[bank:local] data/bank.json 不是合法 JSON: ${e.message}`)
  process.exit(1)
}
const errors = validateBank(data)
if (errors.length) {
  console.error(`[bank:local] 题库校验失败，未安装：`)
  for (const e of errors.slice(0, 20)) console.error('  - ' + e)
  process.exit(1)
}

await mkdir(path.dirname(OUT_DATA), { recursive: true })
await writeFile(OUT_DATA, JSON.stringify(data), 'utf-8')
const gen = `// AUTO-GENERATED by tools/bank-local.mjs — do not edit, do not commit.
// Contains the LOCAL full course bank (git-ignored). Never commit this file.
import local from '../../data/local-bank.json'
import type { BankData } from './types'
export const LOCAL_BANK: BankData | null = local as unknown as BankData
`
await writeFile(OUT_TS, gen, 'utf-8')
const byType = {}
for (const q of data.questions) byType[q.type] = (byType[q.type] ?? 0) + 1
console.log(`[bank:local] 已安装本地题库：${data.questions.length} 题`, JSON.stringify(byType))
console.log('[bank:local] 注意：data/local-bank.json 与 src/lib/local-bank.generated.ts 均已被 .gitignore 忽略')
